"""Board-side code shared by every capture program.

Not a module the board imports: `ttcap.mp.build()` concatenates this file
with one program body (`capture_rp2.py`, ...) and a `CFG` dict prepended by
`ttcap.mp.with_cfg()`, and the result runs as one script in the REPL's
globals. The board has no package path for these files, and one script is
also one compile, which is what the heap budget is measured against (see
MEMORY below). So everything here is a module-level name the body can use
directly, and the body is free to read any of the constants below.

CFG keys every program reads (a body documents its own on top of these):

    clk_gpio     absolute GPIO carrying the project clock (rp_projclk)
    in_base      absolute GPIO the sampled window starts at
    in_count     bits sampled per clock edge (12 on RP2040, 8 on RP2350)
    uo_gpios     the eight absolute uo_out GPIOs -- the only pads a capture
                 may configure; the window can also span pins the RP2
                 itself drives (RP2040 ui_in[0..3] at GPIO 9..12)
    gpio_base    PIO GPIO base: 0, or 16 on RP2350 where uo_out is GPIO 33+
    push_thresh  autopush threshold in bits: 24 for 12-bit x2, 32 for 8-bit x4
    edge         "falling" (default) or "rising" project-clock edge to sample
    pio          PIO block index; 1 by default, *not* 0 -- the stock
                 firmware keeps its own program (the FPGA loader) in PIO0,
                 which on RP2350 also blocks moving that block's pin window
    sm           state machine index within that block (0)
    sysclk_hz    informational; a capture never changes the system clock

Output: a program emits only vgacap chunks after the host-written `VGCH`
header (`vgacap.stream.Writer`), which knows the signal map, mode and clock.
The raw REPL terminates stdout with a 0x04 byte and does not escape the
payload, so a host that scans for 0x04 stops early. Every chunk is `4-byte
tag + u32 length + payload` and nothing else is printed, so the host reads
length-driven instead (`ttcap.repl.RawRepl.exec_chunks`).

Sampling: the project clock is generated by the RP2040/RP2350 itself, so the
sampler is purely a slave. The state machine spins at full system clock,
waits for the clock line to go high and then low (the falling edge, by which
time the project outputs have settled), samples the input window, and wraps.
For `edge == "rising"` the two waits are swapped.

Bit packing -- why the ISR shifts LEFT. The PIO always pushes all 32 ISR
bits; only the shift *counter* is compared against the autopush threshold
(RP2040 datasheet 3.4.4 IN, 3.5.4 autopush). Shifting left, data enters at
the LSB end and earlier samples move toward the MSB, so after
`samples_per_word` samples the word is right-aligned with sample 0 in the
top occupied slot: for 12-bit x2, samples 0xABC and 0x123 pack to
0x00ABC123. That is exactly `sample_bits=12, samples_per_word=2,
flags=VGACAP_FLAG_FIRST_SAMPLE_MSB`, the header the host writes, and it
holds for 8-bit x4 at threshold 32 too. Shifting right would leave the
12-bit pair in bits 31:8 -- left-justified, which no `flags` value can
express and which `vgacap.stream.unpack_words()` cannot decode.

Constants inside a PIO program must be closure variables, not module
globals: `rp2.asm_pio` clears the decorated function's `__globals__` for the
duration of its two assembly passes and installs only the instruction
mnemonics (micropython v1.24.0 ports/rp2/modules/rp2.py:257-259), so a
`LOAD_GLOBAL` of a CFG-derived name raises NameError on the board. Hence
each program's `make_*()` builder takes its operands as parameters: they
become cells, which `LOAD_DEREF` reaches regardless of the globals swap.

Registers (pico-sdk `addressmap.h`, `hardware/structs/pio.h`, `dreq.h`,
`hardware/structs/dma.h`; the host mirrors the PIO arithmetic in
`ttcap.boards.rxf_addr`/`rx_dreq`):

    PIO block base   0x50200000 + 0x100000 * pio
                     RP2040: PIO0 0x50200000, PIO1 0x50300000
                     RP2350: adds PIO2 0x50400000 -- same formula
    RXFn             base + 0x20 + 4 * sm     (the DMA read address)
    FDEBUG           base + 0x08              (RXSTALL = bits 0..3, W1C)
    RX DREQ          8 * pio + 4 + sm         (TX DREQs are 8 * pio + sm)

    DMA block base   0x50000000, channel stride 0x40
    CHn_READ_ADDR    + 0x00        CHn_WRITE_ADDR   + 0x04
    CHn_TRANS_COUNT  + 0x08        CHn_CTRL_TRIG    + 0x0c   (writing this
                                                              STARTS the
                                                              channel)
    CHn_AL1_CTRL     + 0x10 ... CHn_AL1_TRANS_COUNT_TRIG + 0x1c
    The DMA constants live with the program that re-arms channels through
    them (`capture_rp2.py`); only the two non-trigger aliases at +0x04 and
    +0x08 are ever written that way, so a re-arm never starts a channel.

Stopping is COOPERATIVE, and that is load-bearing. `micropython.kbd_intr(-1)`
turns Ctrl-C back into an ordinary byte for the duration of a capture, and
a program checks stdin for it (`stop_requested()`) only *between* chunk
writes. A raised `KeyboardInterrupt` could not do that: on rp2
`mp_hal_stdout_tx_strn()` blocks for CDC TX space and runs pending handlers
while it waits, so the exception lands inside `out.write()` -- which is
where most of a 16 KB chunk's wall-clock time is spent. Measured on fpga-1:
a capture stopped that way cut a chunk at 2183 of 16388 declared bytes, the
host then read the raw-REPL trailer as payload, and a clean 9-frame capture
was reported as a 30 s timeout. Between chunks there is nothing to truncate.

The project clock pad is never configured. Driving it through
`machine.Pin(clk, Pin.IN)` takes the pad away from the firmware's PWM and
stops the clock outright, and the PIO's `wait gpio` reads the pad's input
synchroniser whatever its FUNCSEL is -- see `init_input_pins()`.

MEMORY. The stock RP2040 firmware leaves roughly 80 KB of free heap, and
compiling a script needs most of it at once, so this prose is a real cost on
the wire: the host ships every part through `ttcap.mp.minify()`, which
strips comments and docstrings while keeping each part's line count, and
`ttcap.mp.locate()` turns a board traceback's line back into a file and a
line. Measured on tt07 (MicroPython v1.24): the unminified 25,358-byte
capture script failed at compile time on some runs -- once reporting
`MemoryError: memory allocation failed, allocating 6934 bytes`, and twice
printing `FATAL: uncaught exception` and halting, which is `nlr_jump_fail`,
an allocation failure where no handler exists; that one needs a power
cycle. Success depended on fragmentation, so it looked intermittent. Each
run also leaves its module-level names (~5 KB) in the REPL's globals; the
host deletes them and collects before the next run
(`ttcap.capture.prepare_board`).
"""

